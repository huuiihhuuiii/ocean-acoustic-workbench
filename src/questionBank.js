export function nextQuestions(bank,previous=[],random=Math.random){
  const candidates=bank.filter(q=>!previous.some(old=>old[1]===q[1]));
  const pool=candidates.length>=4?candidates:[...bank];
  for(let i=pool.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[pool[i],pool[j]]=[pool[j],pool[i]];}
  return pool.slice(0,4);
}
